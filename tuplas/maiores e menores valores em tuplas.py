from random import randint
sorteio= (randint(0,10,) ,randint(0,10), randint(0,10)
            ,randint(0,10),randint(0,10))
print(f'eu sortiei os valores: {sorteio}')
print(f'o maior valor sorteado foi {max(sorteio)}') #max: para saber o maior valor.
print(f'o menor valor sorteado foi {min(sorteio)}') #min: para saber o menor valor.
